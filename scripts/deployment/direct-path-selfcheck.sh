#!/usr/bin/env bash
# Optional local self-check for the direct-path kit (GUG-543). Not run in CI.
#
# Renders every direct-path layer's tfvars with scripts/deployment/direct-path.py
# from a config and saved upstream outputs (by default the example config and
# the synthetic fixtures in tests/fixtures/direct_path), then proves each root's
# variable validations and plan-time preconditions accept them: each root and
# the modules it references are copied to a temporary directory outside the
# repository and run with `terraform test` (command = plan) against mock AWS
# providers. Nothing touches AWS, the repository's .terraform directories or its
# lock files.
#
# Mocks: cicd's aws_caller_identity/aws_partition data sources return the
# configured account and "aws" (as the real account would), and the edge ACM
# certificate exposes its DNS validation option at plan time (as the AWS
# provider does). Everything else is a plain mock_provider.
#
# Usage: scripts/deployment/direct-path-selfcheck.sh [--config FILE] [--fixtures DIR]
#        [--layer NAME]... [--keep]
# Terraform needs provider installation; set TF_PLUGIN_CACHE_DIR to reuse a cache.
# Known root bugs B1-B4 in docs/operations/direct-path-deployment.md still fail
# identity-control-plane and edge-identity on this branch.
set -euo pipefail
IFS=$'\n\t'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
KIT="${SCRIPT_DIR}/direct-path.py"
PYTHON="${PYTHON:-python3}"
TERRAFORM="${TERRAFORM:-terraform}"

CONFIG="${REPO_ROOT}/deployment/direct-path/deployment.example.yaml"
FIXTURES="${REPO_ROOT}/tests/fixtures/direct_path"
KEEP=false
SELECTED=()

die() {
  printf 'FAIL: %s\n' "$*" >&2
  exit 2
}

require_value() {
  [[ $# -ge 2 && -n "$2" && "$2" != --* ]] || die "$1 requires a value"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --config) require_value "$@"; CONFIG="$2"; shift 2 ;;
    --fixtures) require_value "$@"; FIXTURES="$2"; shift 2 ;;
    --layer) require_value "$@"; SELECTED+=("$2"); shift 2 ;;
    --keep) KEEP=true; shift ;;
    -h|--help) sed -n '2,22p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

[[ -f "$CONFIG" ]] || die "config not found: ${CONFIG}"
[[ -f "${FIXTURES}/services.inputs.json" ]] || die "missing ${FIXTURES}/services.inputs.json"
compgen -G "${FIXTURES}/outputs/*.outputs.json" >/dev/null || die "no ${FIXTURES}/outputs/*.outputs.json"
command -v "$TERRAFORM" >/dev/null 2>&1 || die "terraform is required"
TF_VERSION="$("$TERRAFORM" version -json | "$PYTHON" -c 'import json, sys; print(json.load(sys.stdin)["terraform_version"])')"
[[ "$TF_VERSION" == 1.14.* ]] || die "terraform 1.14.x is required by the roots (found ${TF_VERSION})"
"$PYTHON" -c 'import yaml' 2>/dev/null || die "PyYAML is required by ${KIT}"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/direct-path-selfcheck.XXXXXX")"
WORK="$(cd "$WORK" && pwd -P)"
case "$WORK/" in
  "$(cd "$REPO_ROOT" && pwd -P)/"*) die "the work directory must be outside the repository" ;;
esac
cleanup() {
  if [[ "$KEEP" == true ]]; then
    printf 'Kept %s\n' "$WORK"
  else
    rm -rf "$WORK"
  fi
}
trap cleanup EXIT

mkdir -p "${WORK}/config" "${WORK}/outputs" "${WORK}/tfvars" "${WORK}/logs" "${WORK}/trees"
cp "$CONFIG" "${WORK}/config/deployment.yaml"
# The example config names services.inputs.json next to itself.
cp "${FIXTURES}/services.inputs.json" "${WORK}/config/services.inputs.json"
cp "${FIXTURES}"/outputs/*.outputs.json "${WORK}/outputs/"

{ read -r ACCOUNT_ID; read -r DOMAIN_NAME; } < <("$PYTHON" - "${WORK}/config/deployment.yaml" <<'PY'
import sys

import yaml

config = yaml.safe_load(open(sys.argv[1], encoding="utf-8"))
print(config["account_id"])
print(config["domain_name"])
PY
)

LAYERS=()
while IFS= read -r layer; do
  LAYERS+=("$layer")
done < <("$PYTHON" "$KIT" layers --names)
[[ ${#LAYERS[@]} -eq 10 ]] || die "expected ten direct-path layers from ${KIT}"
if [[ ${#SELECTED[@]} -gt 0 ]]; then
  for layer in "${SELECTED[@]}"; do
    printf '%s\n' "${LAYERS[@]}" | grep -qx -- "$layer" || die "unknown layer: ${layer}"
  done
fi

write_test_file() {
  local layer="$1"
  local path="$2"
  {
    printf '# Generated by scripts/deployment/direct-path-selfcheck.sh: mock AWS, plan only.\n'
    printf 'mock_provider "aws" {}\n\n'
    case "$layer" in
      cicd)
        cat <<HCL
override_data {
  target = module.cicd.data.aws_caller_identity.current
  values = { account_id = "${ACCOUNT_ID}" }
}

override_data {
  target = module.cicd.data.aws_partition.current
  values = { partition = "aws" }
}

HCL
        ;;
      edge)
        cat <<HCL
mock_provider "aws" {
  alias           = "us_east_1"
  override_during = plan

  mock_resource "aws_acm_certificate" {
    defaults = {
      arn = "arn:aws:acm:us-east-1:${ACCOUNT_ID}:certificate/00000000-0000-4000-8000-000000000000"
      domain_validation_options = [{
        domain_name           = "${DOMAIN_NAME}"
        resource_record_name  = "_selfcheck.${DOMAIN_NAME}."
        resource_record_type  = "CNAME"
        resource_record_value = "_selfcheck.acm-validations.aws."
      }]
    }
  }
}

HCL
        ;;
    esac
    printf 'run "direct_path_inputs_plan" {\n  command = plan\n}\n'
  } > "$path"
}

copy_tree() {
  local layer="$1"
  local tree="$2"
  mkdir -p "${tree}/roots" "${tree}/modules"
  rsync -a --exclude '.terraform/' --exclude 'tests/' "${REPO_ROOT}/roots/${layer}" "${tree}/roots/"
  local module
  while IFS= read -r module; do
    [[ -n "$module" ]] || continue
    rsync -a --exclude '.terraform/' --exclude 'tests/' --exclude '.terraform.lock.hcl' \
      "${REPO_ROOT}/modules/${module}" "${tree}/modules/"
  done < <(sed -n 's|^[[:space:]]*source[[:space:]]*=[[:space:]]*"\.\./\.\./modules/\([A-Za-z0-9_-]*\)".*|\1|p' "${REPO_ROOT}/roots/${layer}"/*.tf | sort -u)
  # modules/edge reads ../../schemas/frontend-config.v3.schema.json.
  rsync -a "${REPO_ROOT}/schemas" "${tree}/"
}

RESULTS=()
FAILURES=0
for layer in "${LAYERS[@]}"; do
  rendered="${WORK}/tfvars/${layer}.tfvars.json"
  if ! "$PYTHON" "$KIT" tfvars "$layer" --config "${WORK}/config/deployment.yaml" \
      --outputs-dir "${WORK}/outputs" --out "$rendered" > "${WORK}/logs/${layer}.render.log" 2>&1; then
    RESULTS+=("FAIL  ${layer}: tfvars rendering ($(tail -n 1 "${WORK}/logs/${layer}.render.log"))")
    FAILURES=$((FAILURES + 1))
    continue
  fi
  if [[ ${#SELECTED[@]} -gt 0 ]] && ! printf '%s\n' "${SELECTED[@]}" | grep -qx -- "$layer"; then
    continue
  fi

  tree="${WORK}/trees/${layer}"
  copy_tree "$layer" "$tree"
  mkdir -p "${tree}/roots/${layer}/tests"
  write_test_file "$layer" "${tree}/roots/${layer}/tests/direct_path.tftest.hcl"

  log="${WORK}/logs/${layer}.terraform.log"
  if ! "$TERRAFORM" -chdir="${tree}/roots/${layer}" init -backend=false -input=false -no-color > "$log" 2>&1; then
    RESULTS+=("FAIL  ${layer}: terraform init (see ${log})")
    FAILURES=$((FAILURES + 1))
    tail -n 20 "$log" >&2
    continue
  fi
  if "$TERRAFORM" -chdir="${tree}/roots/${layer}" test -no-color \
      -filter=tests/direct_path.tftest.hcl -var-file="$rendered" >> "$log" 2>&1; then
    RESULTS+=("PASS  ${layer}: validations and plan-time preconditions accept ${layer}.tfvars.json")
  else
    RESULTS+=("FAIL  ${layer}: terraform test (see ${log})")
    FAILURES=$((FAILURES + 1))
    tail -n 40 "$log" >&2
  fi
done

printf '\nDirect-path self-check (terraform %s, mock AWS providers, plan only):\n' "$TF_VERSION"
printf '  %s\n' ${RESULTS[@]+"${RESULTS[@]}"}
if [[ "$FAILURES" -gt 0 ]]; then
  KEEP=true
  printf 'FAIL: %d layer(s) failed\n' "$FAILURES" >&2
  exit 1
fi
printf 'PASS: every selected root accepts the rendered tfvars\n'
